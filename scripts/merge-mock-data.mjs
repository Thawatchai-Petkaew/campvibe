// merge-mock-data.mjs — Stage 0 (province coverage 10→77) merge step.
//
// History note: the original merge combined a 48-camp curated set + an 80-camp
// "individual-heavy" set (prisma/data/mock-staging-80.json) into the currently
// committed prisma/data/mock-staging-all.json (128 camps / 65 hosts / 10
// provinces). That 80-set generator is a local-only script (per .gitignore's
// "/scripts/*" utility-scripts convention) and is not present in this checkout,
// so it cannot be regenerated here — the CURRENTLY COMMITTED mock-staging-all.json
// IS the preserved baseline for it (never regenerated, never deleted).
//
// This script therefore merges forward, not from scratch:
//   BASE = prisma/data/mock-staging-all.json  (existing, committed — 48+80, 10 provinces)
//   GEN  = prisma/data/mock-staging.json       (freshly regenerated by gen-mock-data.mjs —
//                                               the SAME 48 curated concepts, byte-identical,
//                                               plus NEW province-fill camps for the other 67)
// Every camp in GEN whose `nameEnSlug` already exists in BASE (i.e. the 48 curated — the
// province-fill camps are numbered idx49+ so they can never collide) is skipped; only the
// genuinely NEW province-fill camps are appended (new hosts, or new campsites merged onto a
// host if a same-keyed host already exists). Result: BASE's 128 stay exactly as they were,
// plus every new province is added on top. Output stays keyed by nameEnSlug/email exactly
// like the original merge (unique-slug + unique-email guarantees re-run identically).
//
// Run: node scripts/gen-mock-data.mjs && node scripts/merge-mock-data.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { PROVINCE_REGION } from './lib/thai-region-data.mjs';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

const BASE = read('prisma/data/mock-staging-all.json'); // existing, committed baseline (128)
const GEN = read('prisma/data/mock-staging.json');       // freshly regenerated (48 curated + province-fill)

// 1. index every slug already present in BASE — GEN camps sharing one are the
//    (unchanged) curated 48 and must be skipped, not duplicated.
const existingSlugs = new Set();
for (const h of BASE.hosts) for (const c of h.campsites ?? []) existingSlugs.add(c.nameEnSlug);

// 2. host reconciliation — same dkey rule as the original merge (COMPANY/PARTNERSHIP
//    merge by businessName; INDIVIDUAL by email), so a region host that happens to
//    share a business identity with an existing host folds into it instead of duplicating.
const byKey = new Map();
const order = [];
const dkey = (h) => (h.businessType !== 'INDIVIDUAL' && h.businessName) ? `BIZ:${h.businessName}` : `EMAIL:${h.email}`;
let merged = 0;
function addHost(h, campsitesOverride) {
  const k = dkey(h);
  const camps = campsitesOverride ?? h.campsites ?? [];
  if (!camps.length && !byKey.has(k)) return; // never register an empty new host
  if (byKey.has(k)) { byKey.get(k).campsites.push(...camps); if (campsitesOverride) merged++; }
  else { const copy = { ...h, campsites: [...camps] }; delete copy.key; byKey.set(k, copy); order.push(k); }
}
BASE.hosts.forEach((h) => addHost(h));
let newCampCount = 0;
// GEN tags every camp `curated: idx<=48 (real named destination) | idx>=49 (province-
// fill, templated name)` — BASE predates that field, so index which slugs GEN marked
// curated BEFORE filtering duplicates out, then backfill it onto the matching BASE
// camp below. This is how the "hero" set (scripts/gen-review-text.mjs's ~30-40
// named/demo camps) stays discoverable after the dedup filter drops GEN's own copies.
const genCuratedSlugs = new Set();
for (const h of GEN.hosts) for (const c of h.campsites ?? []) if (c.curated) genCuratedSlugs.add(c.nameEnSlug);
for (const h of GEN.hosts) {
  const newCamps = (h.campsites ?? []).filter((c) => !existingSlugs.has(c.nameEnSlug));
  newCampCount += newCamps.length;
  if (newCamps.length) addHost(h, newCamps);
}
const hosts = order.map((k) => byKey.get(k));
// Backfill `curated` onto every camp that predates the field (BASE's original 128):
// the 48 curated overlap → true (via genCuratedSlugs); the historical 80 individual-
// heavy set → false (never a "named/real destination" camp — no curated concept ever
// produced them). A camp that already carries the field (every GEN-sourced addition
// above) is left untouched.
for (const h of hosts) for (const c of h.campsites) {
  if (c.curated === undefined) c.curated = genCuratedSlugs.has(c.nameEnSlug);
}

// 3. unique emails across hosts (defensive — region hosts use fresh @regioncamp.co.th emails)
const seenEmail = new Set();
for (const h of hosts) { let e = h.email, i = 1; while (seenEmail.has(e)) { e = h.email.replace('@', `+${i}@`); i++; } h.email = e; seenEmail.add(e); }

// 4. unique slugs across all camps (defensive reslug on any accidental collision) + fix image paths
const seenSlug = new Set();
let reslugged = 0;
for (const h of hosts) {
  for (const c of h.campsites) {
    let base = c.nameEnSlug, slug = base, i = 2;
    while (seenSlug.has(slug)) { slug = `${base}-${i}`; i++; }
    seenSlug.add(slug);
    if (slug !== c.nameEnSlug) {
      reslugged++;
      const old = c.nameEnSlug;
      const fix = (p) => p ? p.split(`/seed/camps/${old}/`).join(`/seed/camps/${slug}/`) : p;
      c.images = (c.images || '').split(',').map((s) => fix(s)).join(',');
      if (c.logo) c.logo = fix(c.logo);
      if (c.imageManifest) c.imageManifest.forEach((m) => { m.path = fix(m.path); });
      c.nameEnSlug = slug;
    }
    c.nameThSlug = `${c.nameEnSlug}-th`; // derive consistently → guaranteed unique
  }
}

// 5. emit combined JSON
let nCamps = 0; for (const h of hosts) nCamps += h.campsites.length;
const provincesSeen = new Set();
const byRegion = { NORTH: 0, NORTHEAST: 0, CENTRAL: 0, EAST: 0, WEST: 0, SOUTH: 0 };
for (const h of hosts) for (const c of h.campsites) {
  provincesSeen.add(c.province);
  const region = PROVINCE_REGION[c.province];
  if (region) byRegion[region]++;
}
const data = {
  meta: {
    generatedFor: 'campvibe-staging',
    variant: 'combined-base+province-fill',
    version: 2,
    totalCampsites: nCamps,
    totalHosts: hosts.length,
    distinctProvinces: provincesSeen.size,
    note: 'merged from the existing mock-staging-all.json baseline (historical 48+80, 10 provinces) + the Stage 0 province-fill camps from the regenerated mock-staging.json (67 new provinces)',
  },
  hosts,
};
fs.writeFileSync(path.join(ROOT, 'prisma/data/mock-staging-all.json'), JSON.stringify(data, null, 2));

// 6. combined image-prompt sheet, grouped by province (kept in sync — the original merge
//    wrote this for the 10-province set; generalized here to all 77 via thailand-locations.json).
const THAILAND_LOCATIONS = read('prisma/data/thailand-locations.json');
const PROV_TH = Object.fromEntries(THAILAND_LOCATIONS.map((p) => [p.nameEn, p.nameTh]));
const rows = [];
for (const h of hosts) for (const c of h.campsites) rows.push({ c, h });
const byProv = {};
for (const r of rows) (byProv[r.c.province] ||= []).push(r);
let nImg = 0;
let md = `# Image Generation Prompts — CampVibe staging (combined ${nCamps} camps, 77 provinces)\n\n`;
md += `> Base (historical 48+80, 10 provinces) + Stage 0 province-fill (67 new provinces) = **${nCamps} campsites · ${hosts.length} hosts**\n>\n`;
md += `> **สไตล์รวม:** ภาพถ่ายเสมือนจริง (photorealistic) บรรยากาศแคมป์ปิ้งในไทย แสงธรรมชาติ ไม่มีตัวอักษร/ลายน้ำบนภาพถ่าย (โลโก้เป็น flat vector ได้) ไม่มีคนหันหน้าชัด · บันทึกตาม path ให้ตรงกับ field รูปใน mock-staging-all.json\n\n`;
for (const provEn of Object.keys(PROV_TH)) {
  const rs = byProv[provEn]; if (!rs) continue;
  const imgs = rs.reduce((s, r) => s + (r.c.imageManifest ? r.c.imageManifest.length : 1), 0);
  md += `## ${provEn} (${PROV_TH[provEn]}) — ${rs.length} ลาน, ${imgs} รูป\n\n`;
  for (const { c, h } of rs) {
    md += `### ${c.nameTh} — ${c.nameEn}  \n`;
    md += `เจ้าของ: ${h.businessName || h.name} (${h.businessType}) · รูป: ${c.imageManifest ? c.imageManifest.length : 1}\n\n`;
    const man = c.imageManifest || [{ path: c.images, role: 'photo', aspect: '16:9', alt: c.nameTh, prompt: '(no prompt)' }];
    for (const m of man) { nImg++; md += `- \`${m.path}\` (${m.aspect}, ${m.role}${m.tag ? `/${m.tag}` : ''}) — _alt:_ ${m.alt}  \n  ${m.prompt}\n`; }
    md += `\n`;
  }
}
fs.writeFileSync(path.join(ROOT, 'docs/mock-data-image-prompts-all.md'), md);

// 7. summary
const bt = { COMPANY: 0, PARTNERSHIP: 0, INDIVIDUAL: 0 };
const campBt = { COMPANY: 0, PARTNERSHIP: 0, INDIVIDUAL: 0 };
let nSpots = 0, nFree = 0, nNP = 0, nLogo = 0;
for (const h of hosts) { bt[h.businessType]++; for (const c of h.campsites) { campBt[h.businessType]++; nSpots += c.spots.length; if (c.isFree) nFree++; if (c.ownershipType === 'NATIONAL_PARK') nNP++; if (c.logo) nLogo++; } }
const pct = (n) => Math.round((n / nCamps) * 1000) / 10;
console.log('✅ wrote prisma/data/mock-staging-all.json');
console.log('✅ wrote docs/mock-data-image-prompts-all.md', `(${nImg} image entries)`);
console.log(`merged hosts: ${merged} same-identity host(s) combined · ${reslugged} slug collision(s) renamed · ${newCampCount} new camp(s) considered from GEN`);
console.log(`campsites=${nCamps}  hosts=${hosts.length}`);
console.log(`hosts by type: INDIVIDUAL ${bt.INDIVIDUAL}, COMPANY ${bt.COMPANY}, PARTNERSHIP ${bt.PARTNERSHIP}`);
console.log(`camps by owner: INDIVIDUAL ${campBt.INDIVIDUAL} (${pct(campBt.INDIVIDUAL)}%), COMPANY ${campBt.COMPANY} (${pct(campBt.COMPANY)}%), PARTNERSHIP ${campBt.PARTNERSHIP} (${pct(campBt.PARTNERSHIP)}%)`);
console.log(`spots=${nSpots}  free=${nFree}  nationalPark=${nNP}  logos=${nLogo}`);
console.log(`STAGE 0 — distinct provinces = ${provincesSeen.size}/77  | camps by region:`, byRegion);
